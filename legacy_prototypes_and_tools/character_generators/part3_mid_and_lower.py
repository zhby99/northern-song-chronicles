def generate_part3(existing_names: set):
    results = list(CURATED_MID_LOWER)
    for item in results:
        existing_names.add(item[0])

    # Target quotas for Part 3:
    # 二流上品: 60 (already have 25 -> need 35)
    # 二流中品: 80
    # 二流下品: 100
    # 三流上品: 110
    # 三流中品: 130
    # 三流下品: 150
    # 不入流: 130
    quotas = [
        ("二流上品", 35, "二流"),
        ("二流中品", 80, "二流"),
        ("二流下品", 100, "二流"),
        ("三流上品", 110, "三流"),
        ("三流中品", 130, "三流"),
        ("三流下品", 150, "三流"),
        ("不入流", 130, "不入流"),
    ]

    # Weight distribution across 21 faction profiles (more weight to Gaibang, Shaolin, Kaifeng, Green Forest, Grand Canal, Independent)
    weights = [
        6,  # 嵩山少林寺
        8,  # 丐帮
        4,  # 五台山
        4,  # 南少林
        5,  # 华山
        4,  # 泰山
        5,  # 峨眉
        4,  # 真武道宗
        3,  # 逍遥派
        4,  # 姑苏慕容
        3,  # 终南隐宗
        3,  # 东海桃花岛
        4,  # 蜀中唐门
        4,  # 青城派
        4,  # 铁掌帮
        6,  # 江淮漕帮
        7,  # 开封府/六扇门
        6,  # 太行/京东绿林盟
        3,  # 星宿派
        6,  # 一品堂/辽国暗桩
        14, # 隐世散人/市井百态
    ]

    for realm_exact, count_needed, tier_group in quotas:
        for _ in range(count_needed):
            prof = RNG.choices(FACTION_PROFILES, weights=weights, k=1)[0]
            loc = RNG.choice(prof["locations"])
            is_monk = prof.get("monk_mode", False) and RNG.random() < 0.78

            if is_monk:
                gender = "男"
                prefix = prof["monk_prefixes"][tier_group]
                for _attempt in range(200):
                    c = RNG.choice(MONK_CHARS)
                    if c != prefix:
                        candidate = prefix + c
                        if candidate not in existing_names:
                            name = candidate
                            break
                else:
                    # Fallback 3-char dharma or lay name
                    for _attempt in range(200):
                        candidate = "释" + prefix + RNG.choice(MONK_CHARS)
                        if candidate not in existing_names:
                            name = candidate
                            break
                title = RNG.choice(["护法僧", "持戒僧", "伏虎僧", "苦行僧", "云游僧", "铁棍僧", "禅武僧", "明心僧", "金刚僧", "罗汉僧"])
            else:
                f_ratio = prof.get("female_ratio", 0.16)
                gender = "女" if RNG.random() < f_ratio else "男"
                surnames = prof.get("surnames", prof.get("lay_surnames", ["张", "李", "王", "赵"]))
                for _attempt in range(500):
                    sn = RNG.choice(surnames)
                    if gender == "女":
                        if RNG.random() < 0.25 and len(sn) == 1:
                            gn = RNG.choice(FEMALE_GIVEN_1)
                        else:
                            gn = RNG.choice(FEMALE_GIVEN_1) + RNG.choice(FEMALE_GIVEN_2)
                    else:
                        if RNG.random() < 0.22 and len(sn) == 1:
                            gn = RNG.choice(MALE_GIVEN_1)
                        else:
                            gn = RNG.choice(MALE_GIVEN_1) + RNG.choice(MALE_GIVEN_2)
                    candidate = sn + gn
                    if candidate not in existing_names:
                        name = candidate
                        break

                ep_pre = RNG.choice(EPITHET_PREFIX)
                ep_suf = RNG.choice(EPITHET_SUFFIX_F if gender == "女" else EPITHET_SUFFIX_M)
                title = ep_pre + ep_suf

            existing_names.add(name)

            if tier_group == "二流":
                age = RNG.randint(24, 54)
            elif tier_group == "三流":
                age = RNG.randint(18, 48)
            else:
                age = RNG.randint(15, 62)

            role = RNG.choice(prof["roles"][tier_group])
            arts = RNG.choice(prof["arts"][tier_group])
            bio = RNG.choice(prof["bio_templates"]).format(loc=loc)

            results.append((name, title, gender, age, prof["faction"], role, loc, realm_exact, arts, bio))

    return results


