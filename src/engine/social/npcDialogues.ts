export function getNpcTalkDialogue(
  npc: {
    id?: string
    name: string
    category?: string
    factionName?: string
    role?: string
    bio?: string
  },
  delta: number,
): string {
  const archetype = classifyNpcArchetype(npc)
  const clamped = clamp(Math.round(delta), -1, 5) as TalkFavorDelta
  return TALK_DIALOGUES[archetype][clamped]
}

export function getNpcGiftDialogue(
  npc: {
    id?: string
    name: string
    category?: string
    factionName?: string
    role?: string
    bio?: string
  },
  reaction: 'liked' | 'neutral' | 'disliked',
  itemName: string,
  giftCategory: GiftPreferenceCategory,
): string {
  const archetype = classifyNpcArchetype(npc)
  const base = GIFT_DIALOGUES[archetype][reaction]
  if (reaction === 'liked') {
    return `${base}（心爱「${giftCategory}·${itemName}」，好感度 2.0×）`
  }
  if (reaction === 'disliked') {
    return `${base}（素厌「${giftCategory}」，好感度 0.2×）`
  }
  return base
}
