export type NpcDialogueArchetype =
  | 'sinister'
  | 'monk'
  | 'taoist'
  | 'general'
  | 'chivalrous'
  | 'scholar'
  | 'lady'
  | 'merchant'
  | 'jianghu'

export type TalkFavorDelta = -1 | 0 | 1 | 2 | 3 | 4 | 5

export function classifyNpcArchetype(npc: {
  id?: string
  name: string
  category?: string
  factionName?: string
  role?: string
  bio?: string
}): NpcDialogueArchetype {
  const text = `${npc.category ?? ''} ${npc.factionName ?? ''} ${npc.role ?? ''} ${npc.bio ?? ''}`

  if (/星宿|毒|一品堂|刺客|杀手|魔|邪|阴/.test(text)) return 'sinister'
  if (/少林|天龙|相国|寺|僧|禅|佛|尼|庵/.test(text)) return 'monk'
  if (/道|全真|武当|青城|真人|道长|观/.test(text)) return 'taoist'
  if (/将|军|卫|骑|禁军|边防|总兵|元帅|狄青|杨/.test(text)) return 'general'
  if (/丐帮|绿林|侠|镖|山寨|草莽|五义|白玉堂|展昭/.test(text)) return 'chivalrous'
  if (/朝廷|学士|知府|侍制|太守|书院|儒|进士|欧阳|包拯|范仲淹|司马|苏/.test(text)) {
    return 'scholar'
  }
  if (/女|娘|姑|妃|后|夫人|小姐|峨眉|灵鹫|红颜/.test(text)) return 'lady'
  if (/商|掌柜|市井|匠|医|药|百工/.test(text)) return 'merchant'
  return 'jianghu'
}

